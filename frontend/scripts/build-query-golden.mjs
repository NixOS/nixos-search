#!/usr/bin/env node
// Writes `tests/QueryGolden/Expected.elm` from the request bodies that
// `tests/QueryGolden/Cases.elm` makes with the current `Search.Query`. Run it
// after an intended change to the query, and examine the diff of the output.

import { execSync } from "child_process";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "fs";
import { createRequire } from "module";
import { tmpdir } from "os";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const FRONTEND_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_PATH = join(FRONTEND_DIR, "tests/QueryGolden/Expected.elm");

// A worker project that sees both `src` and `tests`, with the dependencies of
// the application.
const tmpDir = mkdtempSync(join(tmpdir(), "nixos-search-query-golden-"));
const elmJson = JSON.parse(
    readFileSync(join(FRONTEND_DIR, "elm.json"), "utf8"),
);
elmJson["source-directories"] = [
    join(FRONTEND_DIR, "src"),
    join(FRONTEND_DIR, "tests"),
    join(tmpDir, "src"),
];
writeFileSync(join(tmpDir, "elm.json"), JSON.stringify(elmJson));
mkdirSync(join(tmpDir, "src"));
writeFileSync(
    join(tmpDir, "src/QueryGoldenWorker.elm"),
    `port module QueryGoldenWorker exposing (main)

import Json.Encode
import QueryGolden.Cases exposing (cases)


port emit : List ( String, String ) -> Cmd msg


main : Program () () ()
main =
    Platform.worker
        { init = \\_ -> ( (), emit (List.map (Tuple.mapSecond (Json.Encode.encode 4)) cases) )
        , update = \\_ _ -> ( (), Cmd.none )
        , subscriptions = \\_ -> Sub.none
        }
`,
);
execSync(
    `${join(FRONTEND_DIR, "node_modules/.bin/elm")} make src/QueryGoldenWorker.elm --output main.js`,
    { cwd: tmpDir, stdio: ["ignore", "ignore", "inherit"] },
);

const require = createRequire(import.meta.url);
const { Elm } = require(join(tmpDir, "main.js"));
const app = Elm.QueryGoldenWorker.init({ flags: null });

app.ports.emit.subscribe((bodies) => {
    const entries = bodies
        .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
        .map(
            ([name, body]) =>
                `( ${JSON.stringify(name)}\n      , """${body.replaceAll("\\", "\\\\")}"""\n      )`,
        );
    writeFileSync(
        OUT_PATH,
        `module QueryGolden.Expected exposing (expected)

{-| Generated by \`scripts/build-query-golden.mjs\`. Do not edit.
-}


expected : List ( String, String )
expected =
    [ ${entries.join("\n    , ")}
    ]
`,
    );
    console.error(`[query-golden] wrote ${bodies.length} bodies to ${OUT_PATH}`);
});
